create table if not exists public.posts (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  title       text not null check (char_length(title) > 0),
  content     text,
  image_url   text,
  video_url   text,
  problem_url text,                       -- link to the LeetCode problem
  difficulty  text check (difficulty in ('Easy', 'Medium', 'Hard')),
  flag        text not null default 'Problem'
              check (flag in ('Problem', 'Question', 'Resource', 'Opinion')),
  upvotes     integer not null default 0,
  author_id   text not null,
  secret_key  text not null,
  repost_id   bigint references public.posts (id) on delete set null
);

create table if not exists public.comments (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  post_id    bigint not null references public.posts (id) on delete cascade,
  content    text not null check (char_length(content) > 0),
  author_id  text not null
);

-- Course instructions: RLS off so the anon key can read/write.
alter table public.posts    disable row level security;
alter table public.comments disable row level security;

